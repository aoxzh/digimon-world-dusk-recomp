#!/usr/bin/env python3
"""Verify A6RE (Digimon World: Dusk, USA rev 0) and prepare ndsrecomp
inputs.

Shared with the Digimon Story: Sunburst port. Dusk is the North American
release of the engine of Digimon Story: Sunburst (A3VJ): identical ARM7 size
(0x289C0), near-identical ARM9. Phase 1 scope: decompress/extract ARM9 and
ARM7, inventory every ARM9 overlay, and emit recompiler seed configs for the
two main modules only. Overlays stay on the runner's live-byte interpreter
tier until Tier-3 coverage seeds are harvested (the documented overlay path);
prepare still writes their full inventory so later bank promotion needs no
re-extraction.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

try:
    import ndspy.codeCompression as code_compression
    import ndspy.rom
except ImportError as exc:
    raise SystemExit(
        "ndspy is required; install requirements.txt into .venv"
    ) from exc


EXPECTED_ROM_SHA1 = "de1a1915e07288ffad654f3f9f2eb730a0fd1d9c"
EXPECTED_ROM_SHA256 = (
    "df9522e07be99c5622e0211d3a50132776784db3fb28f42fc7392f588e1ae8cb"
)
EXPECTED_ROM_SIZE = 0x04000000
EXPECTED_GAME_CODE = b"A6RE"
EXPECTED_TITLE = b"DS2_USA_DUSK"
EXPECTED_REVISION = 0

# Overlays that load at or above this address target DSi-exclusive memory and
# are never mapped when the cartridge boots as a DS title.
DS_MAIN_RAM_LIMIT = 0x02400000


def sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def write_module_config(
    path: Path,
    *,
    name: str,
    program_id: str,
    cpu: str,
    isa: str,
    load_address: int,
    entry_pc: int,
    binary: bytes,
) -> None:
    lines = [
        "# AUTO-GENERATED by tools/prepare_dusk.py; do not commit.",
        "[program]",
        f"name = {toml_string(name)}",
        f"id = {toml_string(program_id)}",
        f"cpu = {toml_string(cpu)}",
        f"isa = {toml_string(isa)}",
        f"load_address = 0x{load_address:08x}",
        f"size = 0x{len(binary):08x}",
        f"entry_pc = 0x{entry_pc:08x}",
        "authoritative_entry_points = false",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1(binary))}",
        "",
        "[[entry_point]]",
        f"addr = 0x{entry_pc:08x}",
        'mode = "arm"',
        'name = "entry"',
        'kind = "rom_header"',
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--overlay-configs",
        action="store_true",
        help="also emit [overlay] seed configs (empty entry sets; placeholder "
        "for bank promotion once coverage seeds exist)",
    )
    args = parser.parse_args()

    rom_bytes = args.rom.read_bytes()
    digest = sha1(rom_bytes)
    if len(rom_bytes) != EXPECTED_ROM_SIZE:
        raise SystemExit(
            f"ROM size mismatch: got {len(rom_bytes)}, expected {EXPECTED_ROM_SIZE}"
        )
    if digest != EXPECTED_ROM_SHA1:
        raise SystemExit(
            f"ROM SHA-1 mismatch: got {digest}, expected {EXPECTED_ROM_SHA1}"
        )
    if rom_bytes[0x0C:0x10] != EXPECTED_GAME_CODE:
        raise SystemExit(
            f"game code mismatch: got {rom_bytes[0x0C:0x10]!r}, "
            f"expected {EXPECTED_GAME_CODE!r}"
        )
    if rom_bytes[0x00:0x0C] != EXPECTED_TITLE:
        raise SystemExit(
            f"game title mismatch: got {rom_bytes[0x00:0x0C]!r}, "
            f"expected {EXPECTED_TITLE!r}"
        )
    if rom_bytes[0x1C] != EXPECTED_REVISION:
        raise SystemExit(
            f"ROM revision mismatch: got {rom_bytes[0x1C]}, "
            f"expected {EXPECTED_REVISION}"
        )

    rom = ndspy.rom.NintendoDSRom(rom_bytes)
    arm9_compressed = bytes(rom.arm9)
    arm9 = code_compression.decompress(arm9_compressed)
    if len(arm9) < len(arm9_compressed):
        # ndspy returned something shorter than the ROM field: treat the
        # stored blob as raw (A6RE rev 0 ships an uncompressed ARM9; the
        # first word 0xe7ffdeff is a real ARM instruction, not a size
        # header).
        arm9 = arm9_compressed
    arm9_was_compressed = len(arm9) != len(arm9_compressed)
    arm7 = bytes(rom.arm7)

    out = args.out.resolve()
    overlays_dir = out / "overlays"
    overlays_dir.mkdir(parents=True, exist_ok=True)
    (out / "arm9.bin").write_bytes(arm9)
    (out / "arm7.bin").write_bytes(arm7)

    write_module_config(
        out / "arm9.toml",
        name="Digimon World Dusk (USA rev 0) ARM9 main",
        program_id="dusk_arm9",
        cpu="arm9",
        isa="armv5te",
        load_address=int(rom.arm9RamAddress),
        entry_pc=int(rom.arm9EntryAddress),
        binary=arm9,
    )
    write_module_config(
        out / "arm7.toml",
        name="Digimon World Dusk (USA rev 0) ARM7",
        program_id="dusk_arm7",
        cpu="arm7",
        isa="armv4t",
        load_address=int(rom.arm7RamAddress),
        entry_pc=int(rom.arm7EntryAddress),
        binary=arm7,
    )

    overlay_manifest: list[dict[str, object]] = []
    for overlay_id, overlay in sorted(rom.loadArm9Overlays().items()):
        data = bytes(overlay.data)
        if len(data) != int(overlay.ramSize):
            raise SystemExit(
                f"overlay {overlay_id} length mismatch: "
                f"{len(data)} != {overlay.ramSize}"
            )
        filename = f"arm9_overlay_{overlay_id:03d}.bin"
        (overlays_dir / filename).write_bytes(data)
        in_main_ram = int(overlay.ramAddress) < DS_MAIN_RAM_LIMIT
        if args.overlay_configs and in_main_ram:
            # Placeholder for bank promotion: no entry points yet, so this
            # config yields an empty bank. Tier-3 coverage seeds must be
            # appended before it produces useful code.
            lines = [
                "# AUTO-GENERATED by tools/prepare_dusk.py; do not commit.",
                "[program]",
                f"name = {toml_string('Digimon World Dusk (USA rev 0) ARM9 overlay ' + str(overlay_id))}",
                f"id = {toml_string(f'dusk_arm9_ov{overlay_id:03d}')}",
                f"load_address = 0x{int(overlay.ramAddress):08x}",
                f"size = 0x{len(data):08x}",
                f"entry_pc = 0x{int(overlay.ramAddress):08x}",
                "authoritative_entry_points = false",
                "",
                "[identity]",
                f"sha1 = {toml_string(sha1(data))}",
                "",
                "[overlay]",
                f"id = {overlay_id}",
                f"bss_size = 0x{int(overlay.bssSize):08x}",
                f"static_init_start = 0x{int(overlay.staticInitStart):08x}",
                f"static_init_end = 0x{int(overlay.staticInitEnd):08x}",
                "",
            ]
            (overlays_dir / f"arm9_overlay_{overlay_id:03d}.toml").write_text(
                "\n".join(lines), encoding="utf-8", newline="\n"
            )
        elif not in_main_ram:
            print(
                f"overlay {overlay_id} at 0x{int(overlay.ramAddress):08x} "
                f"loads outside DS main RAM; no seed config emitted"
            )
        overlay_manifest.append(
            {
                "id": overlay_id,
                "file": filename,
                "file_id": int(overlay.fileID),
                "load_address": f"0x{int(overlay.ramAddress):08x}",
                "size": int(overlay.ramSize),
                "bss_size": int(overlay.bssSize),
                "static_init_start": f"0x{int(overlay.staticInitStart):08x}",
                "static_init_end": f"0x{int(overlay.staticInitEnd):08x}",
                "compressed_in_rom": bool(overlay.compressed),
                "compressed_size": int(overlay.compressedSize),
                "sha1": sha1(data),
            }
        )
    (out / "overlays.json").write_text(
        json.dumps(overlay_manifest, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    print(f"ROM verified: A6RE revision {EXPECTED_REVISION}, SHA-1 {digest}")
    print(
        f"ARM9: {len(arm9_compressed):,} bytes in ROM "
        f"(compressed={arm9_was_compressed}) -> {len(arm9):,} bytes at "
        f"0x{int(rom.arm9RamAddress):08X}, entry 0x{int(rom.arm9EntryAddress):08X}"
    )
    print(
        f"ARM7: {len(arm7):,} bytes at 0x{int(rom.arm7RamAddress):08X}, "
        f"entry 0x{int(rom.arm7EntryAddress):08X}"
    )
    print(f"ARM9 overlays: {len(overlay_manifest)} extracted and inventoried")
    print(f"Prepared ignored inputs under {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
